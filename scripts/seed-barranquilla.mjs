async function seed() {
  console.log('🌱 Iniciando seed de restaurantes de Barranquilla...')

  for (const restaurant of RESTAURANTS) {
    // Verificar si ya existe
    const { data: existing } = await supabase
      .from('stores')
      .select('id')
      .eq('slug', restaurant.slug)
      .single()

    if (existing) {
      console.log(`⏭️  ${restaurant.name} ya existe, actualizando...`)
      const { error } = await supabase
        .from('stores')
        .update(restaurant)
        .eq('slug', restaurant.slug)
      if (error) console.error(`❌ Error actualizando ${restaurant.name}:`, error)
      else console.log(`   ✅ ${restaurant.name} actualizado`)
    } else {
      const { error } = await supabase
        .from('stores')
        .insert(restaurant)
      if (error) console.error(`❌ Error insertando ${restaurant.name}:`, error)
      else console.log(`   ✅ ${restaurant.name} creado`)
    }
  }

  console.log('🎉 Seed completado')
}

